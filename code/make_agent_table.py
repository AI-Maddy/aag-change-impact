#!/usr/bin/env python3
"""Turn the Colab run's scores.json into the LaTeX rows of Table VIII.
Usage: python3 make_agent_table.py ../results/agents/scores.json OUT_DIR
Writes tab_agents.tex (rows of Table VIII)."""
import json, os, sys

S = json.load(open(sys.argv[1])); out = sys.argv[2]
a, e, i3, p3, m = S["a1"]["ALL"], S["a1_end_to_end"], S["impact"]["ALL"], S["a3"]["ALL"], S["meta"]
f3 = lambda x: "--" if x is None else f"{x:.3f}"
pc = lambda x: "--" if x is None else f"{100 * x:.1f}\\%"

ff = lambda x: f"{x:,.0f}"
core_prec = S.get("core_precision_impact")
rows = [
    ("A1", f"Exactly correct proposals (of {int(a['n'])})", f"{int(a['exact'])}", pc(a["exact_rate"])),
    ("", "Proposals omitting a true entry", f"{int(a['with_omission'])}", pc(a["items_with_omission_rate"])),
    ("", "\\quad rejected by the checks", f"{int(a['bad_rejected'])}", pc(a["bad_rejected_share"])),
    ("", "Correct proposals rejected", f"{int(a['good_rejected'])}", "--"),
    ("", "Entries beyond the true scope", ff(a["invented"]), f"true: {ff(a['true'])}"),
    ("", f"Recall, {int(e['true.n'])} scenarios: true scopes", f3(e["true.recall"]), f"effort {e['true.effort_ratio']:.2f}"),
    ("", "\\quad agent scopes, no checks", f3(e["agent_nochecks.recall"]), f"effort {e['agent_nochecks.effort_ratio']:.2f}"),
    ("", "\\quad agent scopes, checks", f3(e["agent_checks.recall"]), f"effort {e['agent_checks.effort_ratio']:.2f}"),
    ("Alone", f"Recall, {int(i3['n'])} scenarios: model alone", f3(i3["recall"]), f"effort {i3['effort_ratio']:.2f}"),
    ("", "\\quad AAG core", f3(i3["core_recall"]), f"effort {i3['core_hours'] / i3['need_h']:.2f}"),
    ("", "Precision: model alone / core", f3(i3["precision"]), f3(core_prec)),
    ("A3", f"Plans accepted by the core ({int(p3['n'])})", pc(p3["plan_valid_rate"]), "--"),
    ("", "Causal paths from a true cause", pc(p3["path_ok_rate"]), f"of {int(p3['path_n'])}"),
    ("", "Extra items proposed / stale", f"{int(p3['extra'])} / {int(p3['extra_stale'])}", f"core missed {int(p3['core_miss'])}"),
    ("", "Recall, core + extras", f3(p3["union_recall"]), f"effort {(p3['core_hours'] + p3['extra_hours']) / p3['need_h']:.2f}"),
]
with open(os.path.join(out, "tab_agents.tex"), "w") as f:
    f.write(f"%% generated by make_agent_table.py from scores.json; model {m['model']}, {m['date']}\n")
    for r in rows:
        f.write(" & ".join(r) + " \\\\\n")
print("wrote tab_agents.tex")
